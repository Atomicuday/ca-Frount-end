import React, { useState, useRef, useEffect, useId } from 'react';
import { ChevronDown, Check, Search, Loader2, AlertCircle, FileText } from 'lucide-react';
import './GlassSelect.css';

/**
 * GlassSelect - Shared ZapDocs accessible dropdown component
 *
 * Supports:
 * - Full-width trigger matching ZapDocs form input styling
 * - Placeholder / Selected name display with Chevron
 * - Search filter inside opened list only
 * - Keyboard navigation (ArrowDown, ArrowUp, Enter, Home, End, Escape, Space)
 * - Outside click & Escape dismissal
 * - Multi-line row with title, category, code, and selection checkmark
 * - Loading, error, and empty search states
 * - High z-index floating panel positioned directly below trigger without clipping
 */
export default function GlassSelect({
  options = [],
  value = '',
  onChange,
  placeholder = 'Select a document template',
  searchable = true,
  searchPlaceholder = 'Search templates…',
  isLoading = false,
  loadingText = 'Loading published templates…',
  error = null,
  hasError = false,
  disabled = false,
  className = '',
  id,
  name,
  ariaLabel = 'Select option',
  leadingIcon = null
}) {
  const [isOpen, setIsOpen] = useState(false);
  const [searchTerm, setSearchTerm] = useState('');
  const [highlightedIndex, setHighlightedIndex] = useState(0);

  const containerRef = useRef(null);
  const triggerRef = useRef(null);
  const searchInputRef = useRef(null);
  const listRef = useRef(null);
  const autoGeneratedId = useId();
  const selectId = id || `glass-select-${autoGeneratedId}`;

  // Find currently selected option
  const selectedOption = options.find((opt) => String(opt.value) === String(value)) || null;

  // Filter options by search term (matches name/label, category, code, description)
  const filteredOptions = options.filter((opt) => {
    if (!searchTerm.trim()) return true;
    const term = searchTerm.toLowerCase().trim();
    const label = String(opt.label || opt.name || '').toLowerCase();
    const category = String(opt.category || '').toLowerCase();
    const code = String(opt.code || '').toLowerCase();
    const desc = String(opt.description || '').toLowerCase();
    return label.includes(term) || category.includes(term) || code.includes(term) || desc.includes(term);
  });

  // Handle outside click dismissal
  useEffect(() => {
    if (!isOpen) return;

    function handleClickOutside(event) {
      if (containerRef.current && !containerRef.current.contains(event.target)) {
        setIsOpen(false);
        setSearchTerm('');
      }
    }
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, [isOpen]);

  // When dropdown opens, focus search input and set initial highlight
  useEffect(() => {
    if (isOpen) {
      setHighlightedIndex(0);
      if (searchable) {
        // Small delay to ensure panel is mounted
        const timer = setTimeout(() => {
          if (searchInputRef.current) {
            searchInputRef.current.focus();
          }
        }, 30);
        return () => clearTimeout(timer);
      }
    } else {
      setSearchTerm('');
    }
  }, [isOpen, searchable]);

  // Keep highlighted item in view while using keyboard arrows
  useEffect(() => {
    if (isOpen && listRef.current) {
      const activeElement = listRef.current.querySelector(`.glass-select-option[data-index="${highlightedIndex}"]`);
      if (activeElement && activeElement.scrollIntoView) {
        activeElement.scrollIntoView({ block: 'nearest' });
      }
    }
  }, [highlightedIndex, isOpen]);

  // Handle selection
  const handleSelectOption = (opt) => {
    if (disabled) return;
    if (onChange) {
      onChange(opt.value, opt);
    }
    setIsOpen(false);
    setSearchTerm('');
    if (triggerRef.current) {
      triggerRef.current.focus();
    }
  };

  // Keyboard navigation on trigger
  const handleTriggerKeyDown = (e) => {
    if (disabled) return;

    if (e.key === 'ArrowDown' || e.key === 'ArrowUp' || e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      setIsOpen(true);
    } else if (e.key === 'Escape' && isOpen) {
      e.preventDefault();
      e.stopPropagation();
      setIsOpen(false);
    }
  };

  // Keyboard navigation inside search and list
  const handleDropdownKeyDown = (e) => {
    if (e.key === 'Escape') {
      e.preventDefault();
      e.stopPropagation();
      setIsOpen(false);
      if (triggerRef.current) {
        triggerRef.current.focus();
      }
    } else if (e.key === 'ArrowDown') {
      e.preventDefault();
      if (filteredOptions.length > 0) {
        setHighlightedIndex((prev) => (prev + 1) % filteredOptions.length);
      }
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      if (filteredOptions.length > 0) {
        setHighlightedIndex((prev) => (prev - 1 + filteredOptions.length) % filteredOptions.length);
      }
    } else if (e.key === 'Home') {
      e.preventDefault();
      setHighlightedIndex(0);
    } else if (e.key === 'End') {
      e.preventDefault();
      if (filteredOptions.length > 0) {
        setHighlightedIndex(filteredOptions.length - 1);
      }
    } else if (e.key === 'Enter') {
      e.preventDefault();
      if (filteredOptions[highlightedIndex]) {
        handleSelectOption(filteredOptions[highlightedIndex]);
      }
    } else if (e.key === 'Tab') {
      // Tab dismisses dropdown
      setIsOpen(false);
    }
  };

  return (
    <div
      ref={containerRef}
      className={`glass-select-wrap ${disabled ? 'is-disabled' : ''} ${className}`}
      onKeyDown={isOpen ? handleDropdownKeyDown : undefined}
    >
      {/* 1. Main Full-Width Trigger Field */}
      <button
        ref={triggerRef}
        type="button"
        id={selectId}
        name={name}
        className={`glass-select-trigger ${isOpen ? 'is-open' : ''} ${hasError ? 'has-error' : ''}`}
        onClick={() => !disabled && setIsOpen(!isOpen)}
        onKeyDown={handleTriggerKeyDown}
        disabled={disabled}
        role="combobox"
        aria-haspopup="listbox"
        aria-expanded={isOpen}
        aria-label={ariaLabel}
        aria-controls={`${selectId}-dropdown`}
      >
        <div className="glass-select-trigger-content">
          {leadingIcon || <FileText size={16} className="glass-select-leading-icon" />}
          <div className="glass-select-label-wrap">
            {selectedOption ? (
              <span className="glass-select-label selected-text">{selectedOption.label || selectedOption.name}</span>
            ) : (
              <span className="glass-select-label placeholder-text">
                {isLoading ? loadingText : placeholder}
              </span>
            )}
          </div>
        </div>

        <ChevronDown size={16} className={`glass-select-arrow ${isOpen ? 'is-open' : ''}`} />
      </button>

      {/* 2. Floating Styled Dropdown Panel (Directly Below Field, Never Inlined When Closed) */}
      {isOpen && (
        <div
          id={`${selectId}-dropdown`}
          className="glass-select-dropdown"
          role="listbox"
          aria-label={ariaLabel}
        >
          {/* 3. Search Bar Inside Opened List Only */}
          {searchable && (
            <div className="glass-select-search-wrap" onClick={(e) => e.stopPropagation()}>
              <Search size={14} className="glass-select-search-icon" />
              <input
                ref={searchInputRef}
                type="text"
                className="glass-select-search-input"
                placeholder={searchPlaceholder}
                value={searchTerm}
                onChange={(e) => {
                  setSearchTerm(e.target.value);
                  setHighlightedIndex(0);
                }}
                aria-label="Filter options"
              />
            </div>
          )}

          {/* Loading State */}
          {isLoading && (
            <div className="glass-select-status glass-select-loading">
              <Loader2 size={15} className="spinning" />
              <span>{loadingText}</span>
            </div>
          )}

          {/* Error State */}
          {!isLoading && error && (
            <div className="glass-select-status glass-select-error">
              <AlertCircle size={15} />
              <span>{error}</span>
            </div>
          )}

          {/* 4. Options List with Scrolling and Keyboard Highlighting */}
          {!isLoading && !error && (
            <div ref={listRef} className="glass-select-options-list">
              {filteredOptions.length === 0 ? (
                <div className="glass-select-empty">
                  No templates matching "{searchTerm}"
                </div>
              ) : (
                filteredOptions.map((opt, idx) => {
                  const isSelected = String(opt.value) === String(value);
                  const isHighlighted = idx === highlightedIndex;

                  return (
                    <div
                      key={opt.value}
                      data-index={idx}
                      role="option"
                      aria-selected={isSelected}
                      className={`glass-select-option ${isSelected ? 'is-selected' : ''} ${
                        isHighlighted ? 'is-highlighted' : ''
                      }`}
                      onClick={() => handleSelectOption(opt)}
                      onMouseEnter={() => setHighlightedIndex(idx)}
                    >
                      <div className="glass-select-option-content">
                        <div className="glass-select-option-header">
                          <span className="glass-select-option-title">{opt.label || opt.name}</span>
                          {opt.code && <span className="glass-select-code-badge">{opt.code}</span>}
                        </div>
                        {(opt.category || opt.description) && (
                          <div className="glass-select-option-meta">
                            {opt.category && <span className="glass-select-category-text">{opt.category}</span>}
                            {opt.category && opt.description && <span className="glass-select-meta-dot">•</span>}
                            {opt.description && (
                              <span className="glass-select-desc-text">{opt.description}</span>
                            )}
                          </div>
                        )}
                      </div>

                      {isSelected && (
                        <div className="glass-select-check-wrap">
                          <Check size={16} className="glass-select-check-icon" />
                        </div>
                      )}
                    </div>
                  );
                })
              )}
            </div>
          )}
        </div>
      )}
    </div>
  );
}
